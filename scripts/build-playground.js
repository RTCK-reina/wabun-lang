// プレイグラウンド向けバンドルを生成する
// src/*.js をひとつのIIFEに結合し、export/import を取り除いて window.WabunLang に公開する

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const srcDir = resolve(__dirname, '../src');
const outDir = resolve(__dirname, '../dist');

const files = ['lexer.js', 'builtins.js', 'parser.js', 'compiler.js', 'runtime.js', 'index.js', 'backends/kageshi.js'];

let bundled = '// AUTO-GENERATED by scripts/build-playground.js — DO NOT EDIT\n';
bundled += '(function() {\n';
bundled += '"use strict";\n';
for (const f of files) {
  let code = readFileSync(resolve(srcDir, f), 'utf8');
  code = code.replace(/^\s*import\s+[^;]+;\s*$/gm, '');
  code = code.replace(/^\s*export\s*\{[^}]+\}\s*;\s*$/gm, '');
  code = code.replace(/^export\s+(default\s+)?/gm, '');
  // backends/kageshi.js の compile を kageshiCompile にリネーム（衝突回避）
  if (f === 'backends/kageshi.js') {
    code = code.replace(/\bfunction compile\b/g, 'function kageshiCompile');
  }
  bundled += `// ===== ${f} =====\n`;
  bundled += code.trim();
  bundled += '\n\n';
}
bundled += `window.WabunLang = { tokenize, parse, compile, makeRuntime, stringify, compileSource, runSource, kageshiCompile };\n`;
bundled += '})();\n';

mkdirSync(outDir, { recursive: true });
const outFile = resolve(outDir, 'wabun.bundle.js');
writeFileSync(outFile, bundled);
console.log(`built ${outFile} (${bundled.length} bytes)`);
